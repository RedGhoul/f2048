import 'package:flutter/material.dart';

enum ThemeType {
  defaultTheme,
  dark,
  nature,
  ocean,
  sunset,
  neon,
  minimal,
}

class GameTheme {
  final ThemeType type;
  final String name;
  final String description;
  final Color backgroundColor;
  final Color boardBackground;
  final Color tileEmpty;
  final Map<int, Color> tileColors;
  final Map<int, Color> tileTextColors;
  final bool isUnlocked;

  GameTheme({
    required this.type,
    required this.name,
    required this.description,
    required this.backgroundColor,
    required this.boardBackground,
    required this.tileEmpty,
    required this.tileColors,
    required this.tileTextColors,
    this.isUnlocked = false,
  });

  Map<String, dynamic> toJson() {
    return {
      'type': type.toString(),
      'name': name,
      'isUnlocked': isUnlocked,
    };
  }

  GameTheme copyWith({bool? isUnlocked}) {
    return GameTheme(
      type: type,
      name: name,
      description: description,
      backgroundColor: backgroundColor,
      boardBackground: boardBackground,
      tileEmpty: tileEmpty,
      tileColors: tileColors,
      tileTextColors: tileTextColors,
      isUnlocked: isUnlocked ?? this.isUnlocked,
    );
  }
}

